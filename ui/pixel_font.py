GLYPHS: Dict[str, List[str]] = {}
for _char, _spec in _RAW.items():
    _rows = _spec.split("|")
    if len(_rows) != GLYPH_H or any(len(r) != GLYPH_W for r in _rows):
        raise ValueError(f"Malformed glyph for {_char!r}")
    GLYPHS[_char] = _rows

_FALLBACK = GLYPHS["?"]


class PixelFont:
    """Renders (and caches) text surfaces from the built-in glyph table."""

    MAX_CACHE = 600

    def __init__(self) -> None:
        self._cache: Dict[Tuple[str, int, Tuple[int, int, int]], object] = {}

    @staticmethod
    def measure(text: str, scale: int) -> Tuple[int, int]:
        if not text:
            return (0, GLYPH_H * scale)
        return (len(text) * ADVANCE * scale - scale, GLYPH_H * scale)

    def render(self, text: str, scale: int, color: Tuple[int, int, int]):
        """Return a transparent ``pygame.Surface`` containing ``text``."""
        import pygame

        text = text.upper()
        key = (text, scale, tuple(color))
        cached = self._cache.get(key)
        if cached is not None:
            return cached
        width, height = self.measure(text, scale)
        surface = pygame.Surface((max(1, width), height), pygame.SRCALPHA)
        for index, char in enumerate(text):
            rows = GLYPHS.get(char, _FALLBACK)
            left = index * ADVANCE * scale
            for y, row in enumerate(rows):
                for x, bit in enumerate(row):
                    if bit == "#":
                        surface.fill(color, (left + x * scale, y * scale, scale, scale))
        if len(self._cache) >= self.MAX_CACHE:
            self._cache.clear()
        self._cache[key] = surface
        return surface
